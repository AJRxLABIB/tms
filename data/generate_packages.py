#!/usr/bin/env python3
"""
Generates the TMS tourism package dataset as JSON.
Bangladesh destinations get hand-written unique descriptions (highest priority,
per the project brief). International destinations use real, correctly-located
places with category-driven content so every entry is genuinely usable rather
than a lorem-ipsum placeholder.
"""
import json, random

random.seed(42)

packages = []

def add(name, country, region, category, lat, lng, price, duration,
        description, history, best_time, climate, entry_fee, opening_hours,
        adventure, family, couple, solo, budget_est, luxury_est,
        activities, foods, hotels, restaurants, attractions, hospitals,
        transport_guide, travel_tips, safety, features=None):
    packages.append({
        "PackageName": name,
        "Country": country,
        "Region": region,
        "PackageType": category,
        "PackageLocation": f"{region}, {country}" if region else country,
        "MapLat": lat, "MapLng": lng,
        "PackagePrice": price,
        "PackageDuration": duration,
        "PackageFetures": features or (", ".join(activities[:3]) + " and more"),
        "PackageDescription": description,
        "PackageDetails": description,
        "meta": {
            "history": history,
            "best_time_to_visit": best_time,
            "climate": climate,
            "entry_fee": entry_fee,
            "opening_hours": opening_hours,
            "adventure_level": adventure,
            "family_suitability": family,
            "couple_suitability": couple,
            "solo_suitability": solo,
            "budget_estimate": budget_est,
            "luxury_estimate": luxury_est,
            "activities": activities,
            "local_foods": foods,
            "nearby_hotels": hotels,
            "nearby_restaurants": restaurants,
            "nearby_attractions": attractions,
            "nearby_hospitals": hospitals,
            "transportation_guide": transport_guide,
            "travel_tips": travel_tips,
            "safety_guidelines": safety,
        }
    })

